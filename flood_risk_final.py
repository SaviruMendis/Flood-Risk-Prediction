# Chi-squared tests
print("\n--- Chi-squared Tests (categorical) ---")
for col in imputation_order:
    if col not in pre_imp.columns or col not in train_df.columns:
        continue
    orig = pre_imp[col].value_counts().sort_index()
    impu = train_df[col].value_counts().sort_index()
    common = orig.index.intersection(impu.index)
    if len(common) < 2:
        continue
    ct = pd.DataFrame({'orig': orig[common], 'impu': impu[common]}).T
    try:
        chi2, p, *_ = chi2_contingency(ct)
        flag = "⚠ different" if p < 0.05 else "✓ similar"
        print(f"  {col}: chi2={chi2:.2f}, p={p:.4f}  {flag}")
    except Exception as e:
        print(f"  {col}: skipped — {e}")

