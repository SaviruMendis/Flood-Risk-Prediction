"""#### Chi-squared Test for Categorical Columns (CatBoost Imputation)"""

from scipy.stats import chi2_contingency

print("Performing Chi-squared test for categorical columns:")
# imputation_order contains the categorical columns that were imputed
for col in imputation_order:
    if col in train_df.columns and col in pre_imputation_df.columns:
        # Create contingency table of original non-missing vs. imputed for comparison
        # We are comparing the distribution of categories.
        original_counts = pre_imputation_df[col].value_counts().sort_index()
        imputed_counts = train_df[col].value_counts().sort_index()

        # Align indices to ensure correct comparison
        common_indices = original_counts.index.intersection(imputed_counts.index)
        if len(common_indices) == 0:
            print(f"\nColumn: {col} - No common categories found for Chi-squared test. Skipping.")
            continue

        aligned_original_counts = original_counts[common_indices]
        aligned_imputed_counts = imputed_counts[common_indices]

        # Ensure there are at least two categories for the test
        if len(aligned_original_counts) > 1 and len(aligned_imputed_counts) > 1:
            # The Chi-squared test checks if there is a significant association between two categorical variables.
            # Here, we treat 'before' and 'after' imputation as two samples of the same categorical variable.
            # The value counts are the observed frequencies.

            # Create a 2xN contingency table
            contingency_table = pd.DataFrame({
                'Original_Non_Missing': aligned_original_counts,
                'Imputed_Full_Data': aligned_imputed_counts
            }).T

            # Chi-squared test requires all expected frequencies to be > 0. If not, results may be unreliable.
            if (contingency_table.sum(axis=0) == 0).any():
                print(f"\nColumn: {col} - Skipping Chi-squared test due to zero marginal totals.")
                continue

            try:
                chi2, p_value, dof, expected = chi2_contingency(contingency_table)
                print(f"\nColumn: {col}")
                print(f"  Chi-squared Statistic: {chi2:.4f}")
                print(f"  P-value: {p_value:.4f}")
                if p_value < 0.05:
                    print("  Interpretation: Significant difference observed (reject null hypothesis - distributions are likely different).")
                else:
                    print("  Interpretation: No significant difference observed (fail to reject null hypothesis - distributions are likely similar).")
            except ValueError as e:
                print(f"\nColumn: {col} - Error during Chi-squared test: {e}. This might happen if all expected frequencies are small or zero.")
        else:
            print(f"\nColumn: {col} - Not enough categories for Chi-squared test. Skipping.")
