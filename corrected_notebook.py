print("Starting CatBoost categorical imputation...")

# Create missing indicators BEFORE imputation
for col in imputation_order:
    if col in train_df.columns:
        train_df[f"{col}_missing"] = train_df[col].isna().astype(int)

# -------------------------------
# Imputation Loop
# -------------------------------
for target_col in imputation_order:

    if target_col not in train_df.columns:
        continue

    if train_df[target_col].isna().sum() == 0:
        print(f"{target_col}: no missing values")
        continue

    print(f"\nImputing: {target_col}")

    features = imputation_features_map[target_col]

    features = [
        f for f in features
        if f in train_df.columns and f != target_col
    ]

    if len(features) == 0:
        print(f"Skipping {target_col} - no valid features")
        continue

    df_temp = train_df[[target_col] + features].copy()

    # ------------------------------------
    # Fill categorical predictor NaNs
    # ------------------------------------
    for col in features:

        if df_temp[col].dtype == 'object':

            df_temp[col] = (
                df_temp[col]
                .astype(str)
                .replace('nan', 'MISSING')
                .fillna('MISSING')
            )

    # ------------------------------------
    # Split known/unknown
    # ------------------------------------
    known_mask = df_temp[target_col].notna()
    unknown_mask = df_temp[target_col].isna()

    df_known = df_temp.loc[known_mask]
    df_unknown = df_temp.loc[unknown_mask]

    if len(df_unknown) == 0:
        continue

    # Renamed X_train, y_train, X_predict to avoid global variable overwrite
    X_train_impute = df_known[features]
    y_train_impute = df_known[target_col].astype(str)

    X_predict_impute = df_unknown[features]

    # ------------------------------------
    # Identify categorical features
    # ------------------------------------
    cat_features = []

    for idx, col in enumerate(features):

        if X_train_impute[col].dtype == 'object':
            cat_features.append(idx)

    try:

        model = CatBoostClassifier(
            iterations=300,
            depth=6,
            learning_rate=0.05,
            loss_function='MultiClass',
            random_seed=42,
            verbose=False
        )

        model.fit(
            X_train_impute,
            y_train_impute,
            cat_features=cat_features
        )

        predictions = model.predict(X_predict_impute)

        train_df.loc[
            df_unknown.index,
            target_col
        ] = predictions.flatten()

        print(
            f"{target_col}: imputed "
            f"{len(df_unknown)} missing values"
        )

    except Exception as e:

        print(
            f"Failed on {target_col}: {e}"
        )

