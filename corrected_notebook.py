        # Ensure there's enough data to perform the test
        if len(original_data) > 1 and len(imputed_data) > 1:
            # The KS test checks if two samples are drawn from the same distribution.
            # A high p-value suggests that we cannot reject the null hypothesis that they are from the same distribution.
            statistic, p_value = ks_2samp(original_data, imputed_data)
            print(f"\nColumn: {col}")
            print(f"  KS Statistic: {statistic:.4f}")
            print(f"  P-value: {p_value:.4f}")
            if p_value < 0.05:
                print("  Interpretation: Significant difference observed (reject null hypothesis - distributions are likely different).")
            else:
                print("  Interpretation: No significant difference observed (fail to reject null hypothesis - distributions are likely similar).")
        else:
            print(f"\nColumn: {col} - Not enough data for KS test after imputation. Skipping.")
